import { readFileSync, writeFileSync } from "node:fs"

const catalogue = JSON.parse(
  readFileSync("public/data/feature-catalogue.json", "utf8"),
)
const viewer = readFileSync("public/human-atlas-3d.html", "utf8")

const dedicatedPatterns = [
  /^(Heart|Right (ventricle|atrium|auricle)|Left (ventricle|atrium|auricle))/i,
  /lung|alveol|bronch/i,
  /kidney|renal|nephron/i,
  /liver|hepatic lobule|gallbladder/i,
  /stomach|small intestine|large intestine|colon|duodenum/i,
  /brain|cerebr|cerebell|brainstem|spinal cord|neuron|nerve|synapse/i,
  /eye|ear|cochlea|tongue|tooth|teeth/i,
  /pancreas|spleen|urinary bladder|thyroid|thymus|adrenal/i,
  /skin|artery|vein|blood vessel/i,
  /temporomandibular|shoulder joint|elbow complex|wrist joint|hip joint/i,
  /knee joint|ankle joint|sacroiliac|atlanto-|intervertebral symphysis/i,
  /pubic symphysis|saddle joint|carpometacarpal/i,
  /mammary gland|uterus|ovary|uterine tube|vagina|female genital/i,
  /testis|epididymis|ductus deferens|seminal vesicle|prostate|penis/i,
  /gluteus maximus|gluteus medius|gluteus minimus|pelvic floor/i,
  /frontal bone|parietal bone|temporal bone|occipital bone|sphenoid bone/i,
  /ethmoid bone|cranial fossa|orbit|foramen magnum/i,
]

const quotedInViewer = (name) =>
  viewer.includes(`'${name}'`) ||
  viewer.includes(`"${name}"`) ||
  viewer.toLowerCase().includes(`'${name.toLowerCase()}'`)

const grouped = new Map()
for (const feature of catalogue.features) {
  const key = `${feature.domain}::${feature.structure}`
  const record = grouped.get(key) ?? {
    domain: feature.domain,
    structure: feature.structure,
    featureIds: [],
    priorities: new Set(),
  }
  record.featureIds.push(feature.featureId)
  record.priorities.add(feature.priority)
  grouped.set(key, record)
}

const structures = [...grouped.values()].map((record) => {
  const dedicated = dedicatedPatterns.some((pattern) =>
    pattern.test(record.structure),
  )
  const tokenEvidence = quotedInViewer(record.structure)
  return {
    domain: record.domain,
    structure: record.structure,
    featureIds: record.featureIds,
    priorities: [...record.priorities],
    evidenceStatus: dedicated
      ? "dedicated-3d-family"
      : tokenEvidence
        ? "code-token-evidence-manual-review"
        : "no-code-evidence",
    scientificStatus: dedicated
      ? "Procedural educational geometry; anatomical validation pending"
      : tokenEvidence
        ? "A name in source is not proof of independent geometry"
        : "No implementation evidence found by conservative source audit",
  }
})

const counts = structures.reduce((result, structure) => {
  result[structure.evidenceStatus] =
    (result[structure.evidenceStatus] ?? 0) + 1
  return result
}, {})

const output = {
  generatedFrom: "public/data/feature-catalogue.json",
  sourceFeatureRows: catalogue.features.length,
  uniqueStructures: structures.length,
  method:
    "Conservative source audit. Dedicated family patterns identify routed procedural detail scenes; exact quoted names only count as token evidence and never prove geometry.",
  counts,
  structures,
}

writeFileSync(
  "docs/excel-feature-coverage.json",
  `${JSON.stringify(output, null, 2)}\n`,
)

const summary = `# Excel Feature Coverage Summary

Generated by \`pnpm audit:features\` from all ${output.sourceFeatureRows.toLocaleString()} workbook-derived feature rows.

## Conservative structure-level result

- Unique curriculum structures: **${output.uniqueStructures.toLocaleString()}**
- Dedicated routed 3D families: **${counts["dedicated-3d-family"] ?? 0}**
- Exact code-token evidence requiring manual geometry review: **${counts["code-token-evidence-manual-review"] ?? 0}**
- No code evidence: **${counts["no-code-evidence"] ?? 0}**

This is deliberately conservative. A text label or curriculum entry is never
treated as implemented 3D geometry. The complete structure-to-feature-ID
ledger is in \`docs/excel-feature-coverage.json\`.

The dedicated models remain procedural educational geometry unless a reviewed
asset and validation record are explicitly supplied. They must not be
described as CT/MRI segmentation, Blender-authored production assets or
validated biomechanics.
`

writeFileSync("docs/excel-feature-coverage-summary.md", summary)
